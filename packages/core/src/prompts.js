/**
 * `{{KEY}}` に値を差し込む。無いキーは空文字。
 * 議事録のプロンプトを編集して {{TRANSCRIPT}} を消してしまうと、文字起こしが渡らず
 * 空の議事録ができてしまう。そのため vars に TRANSCRIPT があるのに置き場所が無ければ末尾に足す。
 */
export function renderPrompt(template, vars = {}) {
  const tpl = String(template ?? '');
  // 値に `$&` などが含まれても置換記号として扱われないよう、関数で差し込む
  let out = tpl.replace(/\{\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}\}/g, (_, key) => {
    const v = vars[key];
    return v == null ? '' : String(v);
  });
  const hasSlot = /\{\{\s*TRANSCRIPT\s*\}\}/.test(tpl);
  if (vars.TRANSCRIPT != null && !hasSlot) {
    out = `${out.replace(/\s+$/, '')}\n\n# 文字起こし\n${vars.TRANSCRIPT}`;
  }
  return out;
}
